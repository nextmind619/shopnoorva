/**
 * Writes src/data/product-cards.ts — slim client-safe catalog (no full PDP payloads).
 */
import fs from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = process.cwd();
const outPath = path.join(ROOT, "src/data/product-cards.ts");

const { products } = await import(
  pathToFileURL(path.join(ROOT, "src/data/products.ts")).href
);

const cards = products.map((p) => ({
  id: p.id,
  slug: p.slug,
  nameAr: p.name.ar,
  price: p.price,
  hero: p.images?.[0]?.url || `/products/${p.slug}/02-premium-hero.webp`,
}));

const source = `/** Auto-generated by scripts/generate-product-cards.mjs — do not edit by hand */
import type { ProductCardSummary } from "@/types";

export const PRODUCT_CARDS: ProductCardSummary[] = ${JSON.stringify(cards, null, 2)};

export function getProductCardById(id: string): ProductCardSummary | undefined {
  return PRODUCT_CARDS.find((p) => p.id === id);
}

export function getProductCardsByIds(ids: string[]): ProductCardSummary[] {
  const out: ProductCardSummary[] = [];
  for (const id of ids) {
    const card = getProductCardById(id);
    if (card) out.push(card);
  }
  return out;
}

export function getFallbackRelatedCards(excludeId: string, limit = 4): ProductCardSummary[] {
  return PRODUCT_CARDS.filter((p) => p.id !== excludeId).slice(0, limit);
}
`;

await fs.writeFile(outPath, source);
console.log(`Wrote ${cards.length} cards to ${outPath}`);
